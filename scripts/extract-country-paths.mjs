/**
 * One-time generator for `components/icons/CountryMapIcon.tsx` data.
 *
 * Reads Natural Earth boundaries (50m resolution) from the `world-atlas`
 * package, projects France / Germany / United Kingdom into a 200×140 viewBox
 * with 12 px padding, and prints SVG path strings + projected city coords to
 * stdout. The output is meant to be pasted into `CountryMapIcon.tsx`.
 *
 * Run with: `node scripts/extract-country-paths.mjs`
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { feature } from "topojson-client";
import { geoMercator, geoPath } from "d3-geo";

const __dirname = dirname(fileURLToPath(import.meta.url));
const topojsonPath = resolve(
  __dirname,
  "..",
  "node_modules",
  "world-atlas",
  "countries-50m.json",
);
const world = JSON.parse(readFileSync(topojsonPath, "utf-8"));
const fc = feature(world, world.objects.countries);

// European bounding box used to drop overseas territories (Guyane, Réunion,
// Falklands, etc.) so the projection focuses on mainland silhouettes.
const EU_BBOX = { minLng: -12, maxLng: 30, minLat: 35, maxLat: 62 };

function inEU([lng, lat]) {
  return (
    lng >= EU_BBOX.minLng &&
    lng <= EU_BBOX.maxLng &&
    lat >= EU_BBOX.minLat &&
    lat <= EU_BBOX.maxLat
  );
}

function polygonInEU(rings) {
  // A polygon is "in EU" if any vertex of the outer ring is in the EU bbox.
  return rings[0].some(inEU);
}

function trimToEU(feature) {
  const g = feature.geometry;
  if (g.type === "Polygon") {
    return polygonInEU(g.coordinates) ? feature : null;
  }
  if (g.type === "MultiPolygon") {
    const kept = g.coordinates.filter(polygonInEU);
    if (kept.length === 0) return null;
    return {
      ...feature,
      geometry: { type: "MultiPolygon", coordinates: kept },
    };
  }
  return feature;
}

const TARGETS = [
  { name: "France", key: "France" },
  { name: "Germany", key: "Germany" },
  { name: "United Kingdom", key: "United Kingdom" },
];

const SITES = [
  { code: "TLS", country: "France", lat: 43.63, lng: 1.37 },
  { code: "HMB", country: "Germany", lat: 53.55, lng: 9.99 },
  { code: "BRE", country: "Germany", lat: 53.07, lng: 8.8 },
  { code: "FIL", country: "United Kingdom", lat: 51.51, lng: -2.58 },
];

const VIEWBOX = { w: 200, h: 140, pad: 12 };

const paths = {};
const projections = new Map();

for (const { name, key } of TARGETS) {
  const raw = fc.features.find((x) => x.properties.name === name);
  if (!raw) {
    console.error(`Country not found: ${name}`);
    continue;
  }
  const f = trimToEU(raw);
  if (!f) {
    console.error(`Country has no EU polygons: ${name}`);
    continue;
  }
  const projection = geoMercator().fitExtent(
    [
      [VIEWBOX.pad, VIEWBOX.pad],
      [VIEWBOX.w - VIEWBOX.pad, VIEWBOX.h - VIEWBOX.pad],
    ],
    f,
  );
  const path = geoPath(projection);
  const d = path(f);
  paths[key] = d;
  projections.set(key, projection);
}

const siteCoords = {};
for (const s of SITES) {
  const projection = projections.get(s.country);
  if (!projection) continue;
  const [x, y] = projection([s.lng, s.lat]);
  siteCoords[s.code] = {
    x: Math.round(x * 10) / 10,
    y: Math.round(y * 10) / 10,
    country: s.country,
  };
}

const out = [];
out.push(
  "// AUTO-GENERATED by scripts/extract-country-paths.mjs — do not edit by hand.",
  "// Re-run the script after changing TARGETS, SITES, or VIEWBOX.",
  "",
  "export const PATHS: Record<string, string> = {",
);
for (const [key, d] of Object.entries(paths)) {
  out.push(`  ${JSON.stringify(key)}: ${JSON.stringify(d)},`);
}
out.push("};", "");

out.push(
  "export const SITE_COORDS: Record<string, { x: number; y: number; country: string }> = {",
);
for (const [code, c] of Object.entries(siteCoords)) {
  out.push(
    `  ${code}: { x: ${c.x}, y: ${c.y}, country: ${JSON.stringify(c.country)} },`,
  );
}
out.push("};", "");

const target = resolve(__dirname, "..", "lib", "country-map-data.generated.ts");
writeFileSync(target, out.join("\n"), "utf-8");
console.log(`Wrote ${target}`);
